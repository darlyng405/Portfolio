let currentLang = localStorage.getItem('lang') || 'es';

function applyLanguage(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else {
        el.innerHTML = translations[lang][key].replace(/\n/g, '<br>');
      }
    }
  });
  // Actualizar texto de botones expandir/cerrar según idioma y estado actual
  document.querySelectorAll('.expand-btn').forEach(btn => {
    const isOpen = btn.closest('.project-card')?.classList.contains('open');
    const labels = { es: { open: '[ Expandir ]', close: '[ Cerrar ]' }, en: { open: '[ Expand ]', close: '[ Close ]' } };
    btn.textContent = labels[lang]?.[isOpen ? 'close' : 'open'] ?? btn.textContent;
  });
  const toggleBtn = document.getElementById('langToggle');
  if (toggleBtn) toggleBtn.textContent = lang === 'es' ? '🇬🇧 EN' : '🇪🇸 ES';
  localStorage.setItem('lang', lang);
  currentLang = lang;
}

document.getElementById('langToggle')?.addEventListener('click', () => {
  const newLang = currentLang === 'es' ? 'en' : 'es';
  applyLanguage(newLang);
});

applyLanguage(currentLang);
